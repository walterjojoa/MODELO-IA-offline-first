from datetime import date, datetime, timedelta, timezone

import pytest

from app.growth import (MIN_DAYS_BETWEEN_WEIGHINGS, POOR_GROWTH_FRACTION, REFERENCE_TGC,
                        Batch, Death, Temperature, Weighing, fit_tgc, project, weight_after)

UTC = timezone.utc
STOCKED = date(2026, 6, 1)
START = datetime(2026, 6, 1, 6, tzinfo=UTC)


def temperatures(celsius, days, every=1.0):
    return [Temperature(START + timedelta(days=every * i), celsius)
            for i in range(int(days / every) + 1)]


def grown(weight_g, tgc, celsius, days):
    """The same model written out separately, so the data is not generated by the code under test."""
    return (weight_g ** (1 / 3) + (tgc / 1000.0) * celsius * days) ** 3


def of_kind(projection, kind):
    return [f for f in projection.findings if f.kind == kind]


# ---------- that the model is right ----------

@pytest.mark.parametrize("tgc, celsius, days", [(2.0, 13.0, 60), (1.4, 11.0, 90), (2.4, 15.0, 45)])
def test_fitting_recovers_the_coefficient_the_data_was_made_with(tgc, celsius, days):
    """
    The round trip. If the model were wrongly rearranged this would fail even though everything
    else looked like it worked.
    """
    weighings = [Weighing(START, 5.0, 30),
                 Weighing(START + timedelta(days=days), grown(5.0, tgc, celsius, days), 30)]
    fitted, pairs = fit_tgc(weighings, temperatures(celsius, days))
    assert fitted == pytest.approx(tgc, abs=0.01)
    assert pairs == 1


def test_trout_grow_with_heat_and_not_with_days():
    """The fact the whole model rests on: same batch, same days, different water."""
    batch = Batch(STOCKED, 10000, 5.0)
    common = dict(weighings=[Weighing(START, 20.0)], days_ahead=60, now=START)

    cold = project(batch, temperatures=temperatures(9.0, 1), **common)
    warm = project(batch, temperatures=temperatures(15.0, 1), **common)

    assert warm.projected_weight_g > cold.projected_weight_g
    # And not marginally: six degrees change the answer appreciably
    assert warm.projected_weight_g > 1.5 * cold.projected_weight_g


def test_one_bad_weighing_does_not_define_the_batch():
    """The median of the pairs, not the last pair: a bad sample does not decide the forecast."""
    days = 30
    weights = [5.0]
    for _ in range(3):
        weights.append(grown(weights[-1], 2.0, 13.0, days))
    weights.append(weights[-1] * 0.6)  # a sample of the small fish of the pond

    weighings = [Weighing(START + timedelta(days=days * i), w) for i, w in enumerate(weights)]
    fitted, pairs = fit_tgc(weighings, temperatures(13.0, days * 4))
    assert fitted == pytest.approx(2.0, abs=0.05)
    assert pairs == 4


# ---------- when the reference is used, and when nothing is projected ----------

def test_a_single_weighing_uses_the_reference_and_says_so():
    projection = project(Batch(STOCKED, 10000), weighings=[Weighing(START, 20.0)],
                         temperatures=temperatures(13.0, 1), now=START)
    assert not projection.tgc_fitted
    assert projection.tgc == REFERENCE_TGC
    assert any("referencia" in n for n in projection.notes)
    assert any("segunda biometría" in n for n in projection.notes)


def test_two_weighings_too_close_together_cannot_fit():
    weighings = [Weighing(START, 20.0), Weighing(START + timedelta(days=5), 22.0)]
    projection = project(Batch(STOCKED, 10000), weighings=weighings,
                         temperatures=temperatures(13.0, 5), now=START + timedelta(days=5))
    assert not projection.tgc_fitted
    assert any("demasiado juntas" in n for n in projection.notes)


def test_without_temperature_nothing_is_projected():
    projection = project(Batch(STOCKED, 10000), weighings=[Weighing(START, 20.0)],
                         temperatures=[], now=START)
    assert projection.projected_weight_g is None
    assert projection.tgc is None
    assert any("temperatura" in n for n in projection.notes)


def test_without_weighings_or_a_stocked_weight_there_is_no_starting_point():
    projection = project(Batch(STOCKED, 10000), temperatures=temperatures(13.0, 10),
                         now=START + timedelta(days=10))
    assert projection.current_weight_g is None
    assert any("pesaje de muestra" in n for n in projection.notes)


def test_the_stocked_weight_serves_when_there_are_no_weighings():
    projection = project(Batch(STOCKED, 10000, 4.0), temperatures=temperatures(13.0, 30),
                         days_ahead=30, now=START + timedelta(days=30))
    assert projection.current_weight_g == 4.0
    assert projection.projected_weight_g > 4.0


# ---------- the harvest date, which is the number the producer wants ----------

def test_it_says_how_many_days_to_market_weight():
    projection = project(Batch(STOCKED, 10000), weighings=[Weighing(START, 50.0)],
                         temperatures=temperatures(13.0, 1), target_weight_g=250.0, now=START)
    assert projection.days_to_target > 0
    assert projection.target_date == (START + timedelta(days=projection.days_to_target)).date()

    # Checked independently: the weight projected to those days has to give the target
    assert grown(50.0, projection.tgc, 13.0, projection.days_to_target) == pytest.approx(250.0, rel=0.02)


def test_already_past_the_target_means_zero_days():
    projection = project(Batch(STOCKED, 10000), weighings=[Weighing(START, 300.0)],
                         temperatures=temperatures(13.0, 1), target_weight_g=250.0, now=START)
    assert projection.days_to_target == 0


# ---------- growth that is going badly ----------

def test_a_batch_losing_weight_is_urgent_and_is_not_projected():
    weighings = [Weighing(START, 40.0), Weighing(START + timedelta(days=30), 36.0)]
    projection = project(Batch(STOCKED, 10000), weighings=weighings,
                         temperatures=temperatures(13.0, 30), now=START + timedelta(days=30))
    found = of_kind(projection, "crecimiento")
    assert len(found) == 1 and found[0].urgent
    assert "no está creciendo" in found[0].message
    # Projecting with a negative coefficient would give a weight falling to zero: it is not done
    assert projection.projected_weight_g is None
    assert any("sin sentido" in n for n in projection.notes)


def test_growing_far_below_what_the_water_allows_says_where_to_look():
    """
    The most useful finding here: the water is fine and the fish still are not growing. That rules
    out temperature and points at ration, density or health, which is what the caretaker can change.
    """
    days = 60
    slow = REFERENCE_TGC * 0.5
    weighings = [Weighing(START, 20.0),
                 Weighing(START + timedelta(days=days), grown(20.0, slow, 14.0, days))]
    projection = project(Batch(STOCKED, 10000), weighings=weighings,
                         temperatures=temperatures(14.0, days), now=START + timedelta(days=days))
    found = of_kind(projection, "crecimiento")
    assert len(found) == 1 and not found[0].urgent
    assert "ración" in found[0].message
    # And it keeps projecting: the batch is growing, just badly
    assert projection.projected_weight_g > projection.current_weight_g


def test_a_batch_growing_well_gets_no_warning():
    days = 60
    weighings = [Weighing(START, 20.0),
                 Weighing(START + timedelta(days=days), grown(20.0, REFERENCE_TGC, 13.0, days))]
    projection = project(Batch(STOCKED, 10000), weighings=weighings,
                         temperatures=temperatures(13.0, days), now=START + timedelta(days=days))
    assert of_kind(projection, "crecimiento") == []


def test_the_poor_growth_threshold_is_a_fraction_of_the_reference():
    assert 0 < POOR_GROWTH_FRACTION < 1


# ---------- survival: a ceiling, and said as one ----------

def test_survival_is_reported_as_a_ceiling():
    projection = project(Batch(STOCKED, 1000),
                         deaths=[Death(START + timedelta(days=10), 250)],
                         temperatures=temperatures(13.0, 30), now=START + timedelta(days=30))
    assert projection.current_quantity == 750
    assert projection.survival_pct == 75.0

    found = of_kind(projection, "mortalidad")
    assert found, "75% is below the 80% expected"
    # What cannot be known, said: fry that die without being recorded are not counted
    assert "techo" in found[0].message
